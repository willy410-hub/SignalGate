"""Constrained data-allocation environment (SIMULATED).

An agent spends a labeling budget in batches. Each action picks a domain, an
annotator tier and a batch size. Buying labels improves a simulated model's
capability in that domain with diminishing returns, scaled by label accuracy.
A step is a *violation* when the batch fails the quality gate: measured
Krippendorff alpha below `alpha_min`, and (when `gold_audit` is on) accuracy on
hidden gold items below `gold_min`.

Tier 3 ("bulk vendor") is cheap and its annotators herd (copy each other), so it
shows very high agreement but low true accuracy. Agreement alone cannot see
that; the hidden-gold audit can.

All numbers are generated by this simulator. Nothing here is human data.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, Optional, Tuple

import gymnasium as gym
import numpy as np
from gymnasium import spaces

DOMAINS = ["support", "finance", "medical"]
TIERS = ["crowd", "trained", "expert", "bulk_vendor"]
BATCH_SIZES = [50, 100, 200]
D, T, B = len(DOMAINS), len(TIERS), len(BATCH_SIZES)
N_ACTIONS = D * T * B + 1  # last action = STOP
STOP = N_ACTIONS - 1
VENDOR = 3

NOMINAL_ACC = np.array(
    [
        [0.95, 0.97, 0.99, 0.62],  # support
        [0.85, 0.94, 0.98, 0.60],  # finance
        [0.70, 0.88, 0.96, 0.58],  # medical
    ]
)
COST_PER_ITEM = np.array([1.0, 2.5, 6.0, 0.5])
DOMAIN_WEIGHT = np.array([0.2, 0.3, 0.5])
C0 = np.array([0.55, 0.40, 0.25])
GAIN_K = np.array([0.9, 0.8, 0.7])
GAIN_SCALE = np.array([300.0, 400.0, 500.0])
HERD_COPY = 0.95


def decode(a: int) -> Tuple[int, int, int]:
    d, rem = divmod(a, T * B)
    t, b = divmod(rem, B)
    return d, t, b


def encode(d: int, t: int, b: int) -> int:
    return d * T * B + t * B + b


@dataclass
class SimConfig:
    acc: np.ndarray = field(default_factory=lambda: NOMINAL_ACC.copy())
    budget: float = 2400.0
    max_steps: int = 24


def train_config(rng: np.random.Generator) -> SimConfig:
    """Training family: nominal accuracies with small random jitter."""
    acc = np.clip(NOMINAL_ACC + rng.normal(0, 0.015, NOMINAL_ACC.shape), 0.5, 0.995)
    return SimConfig(acc=acc)


def heldout_config(rng: np.random.Generator, shift: float = 0.08) -> SimConfig:
    """Held-out family: crowd and trained annotators are worse than calibration
    suggested in finance and medical (e.g. a new labeling population)."""
    acc = NOMINAL_ACC.copy()
    acc[1:, 0:2] -= rng.uniform(shift * 0.5, shift * 1.25, size=(D - 1, 2))
    acc += rng.normal(0, 0.01, acc.shape)
    return SimConfig(acc=np.clip(acc, 0.5, 0.995))


def fast_alpha_binary(labels: np.ndarray) -> float:
    """Krippendorff's alpha (nominal) for complete binary data, vectorised.
    Verified equal to sgate_eval.annotation.krippendorff_alpha in the tests."""
    k = labels.sum(axis=1).astype(float)
    m = labels.shape[1]
    n = labels.size
    n1 = k.sum()
    n0 = n - n1
    if n1 == 0 or n0 == 0:
        return 1.0
    o_off = 2.0 * (k * (m - k) / (m - 1)).sum()
    return float(1.0 - o_off * (n - 1) / (2.0 * n0 * n1))


def sample_batch(rng: np.random.Generator, acc: float, n: int, herd: bool, n_annot: int = 3):
    truth = rng.integers(0, 2, n)
    first = np.where(rng.random(n) < acc, truth, 1 - truth)
    rest_indep = np.where(rng.random((n, n_annot - 1)) < acc, truth[:, None], 1 - truth[:, None])
    if herd:
        copy = rng.random((n, n_annot - 1)) < HERD_COPY
        rest = np.where(copy, first[:, None], rest_indep)
    else:
        rest = rest_indep
    labels = np.concatenate([first[:, None], rest], axis=1)
    majority = (labels.sum(axis=1) * 2 > n_annot).astype(int)
    return truth, labels, majority


def measure_batch(rng, acc, n, herd, gold_frac: float = 0.1, min_gold: int = 10):
    truth, labels, majority = sample_batch(rng, acc, n, herd)
    alpha = fast_alpha_binary(labels)
    g = max(min_gold, int(n * gold_frac))
    gold_acc = float(np.mean(majority[:g] == truth[:g]))
    true_acc = float(np.mean(majority == truth))
    return alpha, gold_acc, true_acc


def calibration_table(rng: np.random.Generator, cfg: SimConfig, n: int = 200) -> np.ndarray:
    """Noisy per-(domain,tier) alpha estimate from one calibration batch each."""
    tab = np.zeros((D, T))
    for d in range(D):
        for t in range(T):
            tab[d, t] = measure_batch(rng, cfg.acc[d, t], n, t == VENDOR)[0]
    return tab


class DataBudgetEnv(gym.Env):
    metadata = {"render_modes": []}

    def __init__(
        self,
        family: str = "train",
        reward_mode: str = "true_gain",   # 'true_gain' | 'agreement'
        gold_audit: bool = True,
        alpha_min: float = 0.7,
        gold_min: float = 0.8,
        reward_scale: float = 10.0,
        shield: bool = False,
        shield_margin: float = 0.05,
        seed: Optional[int] = None,
    ):
        super().__init__()
        assert family in ("train", "heldout") and reward_mode in ("true_gain", "agreement")
        self.family, self.reward_mode, self.gold_audit = family, reward_mode, gold_audit
        self.alpha_min, self.gold_min, self.reward_scale = alpha_min, gold_min, reward_scale
        self.shield, self.shield_margin = shield, shield_margin
        self.observation_space = spaces.Box(-1.0, 2.0, shape=(2 + D + D * T,), dtype=np.float32)
        self.action_space = spaces.Discrete(N_ACTIONS)
        self.rng = np.random.default_rng(seed)
        self._cal_rng = np.random.default_rng(12345)  # fixed calibration process
        self._calib = calibration_table(self._cal_rng, SimConfig())  # calibrated once, on NOMINAL conditions
        self.reset()

    # ----- helpers -------------------------------------------------------
    def _obs(self) -> np.ndarray:
        return np.concatenate(
            [[self.budget / self.cfg.budget, self.t / self.cfg.max_steps], self.c, self.est_alpha.ravel()]
        ).astype(np.float32)

    def action_mask(self) -> np.ndarray:
        mask = np.zeros(N_ACTIONS, dtype=bool)
        for a in range(N_ACTIONS - 1):
            d, t, b = decode(a)
            if BATCH_SIZES[b] * COST_PER_ITEM[t] > self.budget + 1e-9:
                continue
            if self.shield and (self._calib[d, t] < self.alpha_min + self.shield_margin or self.blocked[d, t]):
                continue
            if self.shield and self.gold_audit and t == VENDOR:  # known-bad vendor per calibration audit
                continue
            mask[a] = True
        mask[STOP] = True
        return mask

    # ----- gym API -------------------------------------------------------
    def reset(self, *, seed=None, options=None):
        if seed is not None:
            self.rng = np.random.default_rng(seed)
        self.cfg = train_config(self.rng) if self.family == "train" else heldout_config(self.rng)
        self.budget = self.cfg.budget
        self.t = 0
        self.c = C0.copy()
        self.est_alpha = self._calib.copy()
        self.blocked = np.zeros((D, T), dtype=bool)
        self.ep_gain = self.ep_proxy = self.ep_viol = self.ep_spend = self.ep_vendor = 0.0
        return self._obs(), {}

    def step(self, action: int):
        action = int(action)
        info: Dict[str, float] = {}
        if action == STOP or not self.action_mask()[action]:
            terminated = True
            return self._obs(), 0.0, terminated, False, {"violation": 0.0, "stopped": 1.0, **self._ep_info()}
        d, t, b = decode(action)
        n = BATCH_SIZES[b]
        cost = n * COST_PER_ITEM[t]
        self.budget -= cost
        self.ep_spend += cost
        alpha, gold_acc, true_acc = measure_batch(self.rng, self.cfg.acc[d, t], n, t == VENDOR)
        self.est_alpha[d, t] = 0.5 * self.est_alpha[d, t] + 0.5 * alpha
        violation = float(alpha < self.alpha_min or (self.gold_audit and gold_acc < self.gold_min))
        if violation:
            self.blocked[d, t] = True
        signal = max(2 * true_acc - 1, 0.0)
        gain = GAIN_K[d] * (1 - self.c[d]) * (1 - np.exp(-n * signal / GAIN_SCALE[d]))
        self.c[d] += gain
        weighted_gain = float(DOMAIN_WEIGHT[d] * gain)
        proxy = n * alpha / 100.0
        self.ep_gain += weighted_gain
        self.ep_proxy += proxy
        self.ep_viol += violation
        self.ep_vendor += float(t == VENDOR)
        self.t += 1
        reward = (weighted_gain if self.reward_mode == "true_gain" else proxy) * self.reward_scale
        min_cost = min(BATCH_SIZES) * COST_PER_ITEM.min()
        terminated = bool(self.budget < min_cost or self.t >= self.cfg.max_steps)
        info = {"violation": violation, "alpha": alpha, "gold_acc": gold_acc, "stopped": 0.0, **self._ep_info()}
        return self._obs(), reward, terminated, False, info

    def _ep_info(self) -> Dict[str, float]:
        return {
            "ep_gain": self.ep_gain, "ep_proxy": self.ep_proxy, "ep_violations": self.ep_viol,
            "ep_spend_frac": self.ep_spend / self.cfg.budget, "ep_vendor_steps": self.ep_vendor,
            "ep_steps": float(self.t),
        }
